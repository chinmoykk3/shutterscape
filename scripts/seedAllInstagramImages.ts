export async function syncAllInstagramPosts() {
  const dotenv = await import('dotenv');
  const { resolve } = await import('path');
  dotenv.config({ path: resolve(process.cwd(), '.env.local') });
  dotenv.config({ path: resolve(process.cwd(), '.env') });

  const mongoose = (await import('mongoose')).default;
  const { connectDB } = await import('../lib/db');

  await connectDB();
  console.log('Connected to MongoDB Atlas');

  const coll = mongoose.connection.collection('galleryitems');

  for (const item of allInstagramGalleryItems) {
    await coll.updateOne(
      { instagramId: item.instagramId },
      {
        $set: {
          ...item,
          updatedAt: new Date(),
        },
      },
      { upsert: true }
    );
  }

  console.log(`Successfully synced ${allInstagramGalleryItems.length} authentic @shutterscape_gcu posts!`);
  const total = await coll.countDocuments({ status: 'published' });
  console.log(`Total published gallery items now in database: ${total}`);
}

// If executed directly from command line
if (process.argv[1]?.includes('seedAllInstagramImages')) {
  syncAllInstagramPosts()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
